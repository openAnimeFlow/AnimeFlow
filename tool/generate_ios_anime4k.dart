// Adapts our generated Anime4K GLES subset to Metal. This is an offline preset
// converter, not a runtime/general GLSL compiler. Run after generate_android_anime4k.dart.
import 'dart:convert';
import 'dart:io';

import 'generate_android_anime4k.dart' show writeGenerated;

void main(List<String> arguments) {
  for (final fixture in [false, true]) {
    final base =
        fixture ? 'test/fixtures/video_shaders' : 'assets/shaders/video_player';
    final preset = fixture ? 'x2' : 'efficiency';
    final passes =
        (jsonDecode(File('$base/android/$preset.json').readAsStringSync())
                as List)
            .cast<Map<String, dynamic>>();
    for (final pass in passes) {
      final glsl = File('$base/android/${pass['asset']}').readAsStringSync();
      final metal = convertShader(glsl.replaceAll('\r\n', '\n'), pass);
      pass['asset'] = (pass['asset'] as String).replaceFirst('.glsl', '.metal');
      writeGenerated(
          '$base/ios/${pass['asset']}', metal, arguments.contains('--check'));
    }
    writeGenerated(
        '$base/ios/$preset.json',
        '${const JsonEncoder.withIndent('  ').convert(passes)}\n',
        arguments.contains('--check'));
    stdout.writeln('Metal $preset: ${passes.length} passes verified.');
  }
}

String convertShader(String glsl, Map<String, dynamic> pass) {
  // Fail on changes outside this converter's small, reviewed source subset.
  if (!glsl.startsWith('#version 300 es\n') ||
      !glsl.endsWith('void main() { outColor = hook(); }\n') ||
      RegExp(r'\b(?:discard|layout|samplerCube|gl_\w+|dFdx|dFdy)\b')
          .hasMatch(glsl)) {
    throw StateError('Unsupported GLES source in ${pass['asset']}');
  }
  final functions =
      RegExp(r'^(?:float|vec[234]|void)\s+(\w+)\s*\(', multiLine: true)
          .allMatches(glsl)
          .map((m) => m[1])
          .toSet();
  if (!functions.containsAll(['main', 'hook']) ||
      functions.difference({'main', 'hook', 'get_luma'}).isNotEmpty) {
    throw StateError('Review new helper functions in ${pass['asset']}');
  }
  final bindings = (pass['bindings'] as List).cast<Map<String, dynamic>>();
  if (bindings.length > 16) throw StateError('Too many Metal texture bindings');
  final args = <String>[
    'VideoVertex in [[stage_in]]',
    'constant float2 *sizes [[buffer(0)]]',
  ];
  final aliases = StringBuffer('#define vTexCoord in.uv\n');
  for (var i = 0; i < bindings.length; i++) {
    final binding = bindings[i];
    final name = binding['name'];
    if (binding['sampler'] == true) {
      args.add('texture2d<float> u_$name [[texture($i)]]');
    }
    if (binding['dimensions'] == true) {
      aliases.writeln('#define s_$name sizes[$i]');
    }
  }
  var source = glsl
      .replaceFirst('#version 300 es\n', '')
      .replaceAll(
          RegExp(
              r'^(?:precision highp float;|in vec2 vTexCoord;|out vec4 outColor;|uniform (?:sampler2D|vec2) \w+;)\n',
              multiLine: true),
          '')
      .replaceFirst('void main() { outColor = hook(); }\n', '')
      .replaceFirst(
          'vec4 hook()', 'fragment float4 videoFragment(${args.join(', ')})')
      .replaceAllMapped(
          RegExp(r'\btexture\((u_\w+),'), (m) => '${m[1]}.sample(videoSampler,')
      .replaceAllMapped(
          RegExp(r'\b(ivec2|vec2|vec3|vec4)\b'),
          (m) => {
                'ivec2': 'int2',
                'vec2': 'float2',
                'vec3': 'float3',
                'vec4': 'float4'
              }[m[1]]!);
  // GLSL scalar-list matrices are column-major, as are these explicit Metal columns.
  source = source.replaceAllMapped(RegExp(r'\bmat4\(([^()]+)\)'), (m) {
    final values = m[1]!.split(',').map((v) => v.trim()).toList();
    if (values.length != 16 || values.any((v) => double.tryParse(v) == null)) {
      throw StateError('Unsupported matrix constructor in ${pass['asset']}');
    }
    return 'float4x4(${[
      for (var i = 0; i < 16; i += 4)
        'float4(${values.sublist(i, i + 4).join(', ')})'
    ].join(', ')})';
  });
  if (RegExp(r'\b(?:uniform|mat4|sampler2D)\b').hasMatch(source)) {
    throw StateError('Unconverted GLES declaration in ${pass['asset']}');
  }
  return '''// Generated by tool/generate_ios_anime4k.dart. Do not edit.
#include <metal_stdlib>
using namespace metal;
struct VideoVertex { float4 position [[position]]; float2 uv; };
constexpr sampler videoSampler(coord::normalized, address::clamp_to_edge, filter::linear);
$aliases
$source''';
}
